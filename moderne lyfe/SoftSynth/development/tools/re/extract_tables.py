#!/usr/bin/env python3
"""Writes src/engine/WaveTables.cpp from the tables in the original's text segment.

Usage: extract_tables.py SOFTSYNT.PRG out.cpp
"""
import struct
import sys

TABLES = (
    ("kSine", 0x16B7A, 4096),
    ("kSquare", 0x1AB7A, 4096),
    ("kTriangle", 0x18B7A, 4096),
    ("kNoise", 0x1CBB2, 16384),
)

with open(sys.argv[1], "rb") as f:
    prg = f.read()
out = ["// Generated by tools/re/extract_tables.py from SOFTSYNT.PRG. Do not edit.",
       '#include "WaveTables.h"', "", "namespace softsynth {", ""]
for name, offset, count in TABLES:
    values = struct.unpack_from(f">{count}h", prg, 28 + offset)
    out.append(f"// Text segment offset {offset:#x}.")
    out.append(f"const int16_t {name}[{count}] = {{")
    for i in range(0, count, 16):
        out.append("    " + ", ".join(str(v) for v in values[i:i + 16]) + ",")
    out += ["};", ""]
out += ["} // namespace softsynth", ""]
with open(sys.argv[2], "w", encoding="ascii", newline="\n") as f:
    f.write("\n".join(out))
